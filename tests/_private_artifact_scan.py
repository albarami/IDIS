"""Closed-list scan for slice100 paths in collected Task 7 and Task 8 tests.

Overlay paths come from ``ALLOWED_ARTIFACTS`` in ``scripts/ci_private_inputs.py``.
CI-regenerated paths come from the check job in ``.github/workflows/ci.yml``.
A collected test may read a slice100 file only when that file is overlay-supplied,
listed on ``requires_private_artifact``, or regenerated by that job.
``assert not path.exists()`` is an absence proof, not a read.
"""

from __future__ import annotations

import ast
import re
from collections.abc import Mapping
from pathlib import Path

import yaml

_OVERLAY_PREFIX = ".local_reports/slice100/"
_READ_METHODS = frozenset({"read", "read_bytes", "read_text"})
_REPO_ROOT = Path(__file__).resolve().parents[1]
_DEFAULT_WORKFLOW = _REPO_ROOT / ".github" / "workflows" / "ci.yml"
_V27_CANDIDATE_MKDIR = "mkdir -p .local_reports/slice100/task8/v27-candidate"
_MATERIALIZE_V27_SCRIPT = "scripts/materialize_full_strict_v27_preimage.py"
_GENERATE_V27_SCRIPT = "scripts/generate_task8_v27_contract_fixtures.py"
_STAGING_OUTPUT_FLAG = "--staging-output"
_CI_REGENERATED_PATH_COUNT = 2
_SHA256_HEX = re.compile(r"^[0-9a-f]{64}$")
_PIN_PAIR = re.compile(rf"(?P<digest>[0-9a-fA-F]+)\s+(?P<path>{re.escape(_OVERLAY_PREFIX)}\S+)")
_PIN_PATH = re.compile(rf"{re.escape(_OVERLAY_PREFIX)}\S+")


def overlay_slice100_paths() -> frozenset[str]:
    """Return slice100-relative paths restored by the P5 overlay manifest."""

    return frozenset(
        path[len(_OVERLAY_PREFIX) :]
        for path in _overlay_manifest_paths()
        if path.startswith(_OVERLAY_PREFIX)
    )


def consumed_slice100_paths(modules: list[Path]) -> set[str]:
    """Return slice100 files read by ``modules``, ignoring absence proofs."""

    found: set[str] = set()
    for path in modules:
        tree = ast.parse(path.read_text(encoding="utf-8"))
        found.update(_consumed_slice100_paths(tree))
    return found


def skip_on_slice100_paths(modules: list[Path]) -> set[tuple[str, str]]:
    """Return tests that call ``pytest.skip`` while naming a slice100 file."""

    found: set[tuple[str, str]] = set()
    for path in modules:
        tree = ast.parse(path.read_text(encoding="utf-8"))
        assigns = _module_assigns(tree)
        bindings = _slice100_bindings(assigns, _repo_root_names(assigns))
        module = path.relative_to(_REPO_ROOT).as_posix()
        for fn in _functions(tree).values():
            if _calls_skip(fn) and _function_reads_slice100_file(fn, bindings):
                found.add((module, fn.name))
    return found


def ci_regenerated_slice100_paths(workflow: Path | None = None) -> frozenset[str]:
    """Return slice100 paths the check job regenerates before pytest.

    Args:
        workflow: Workflow YAML. Defaults to ``.github/workflows/ci.yml``.

    Returns:
        The slice100-relative paths named by the materialize ``--staging-output``,
        the generate ``--staging-output``, and the sha256 pin lines.

    Raises:
        AssertionError: The check job does not have exactly one regeneration step,
            or those three sources do not name exactly two paths.
    """

    return frozenset(_ci_regenerated_pins(workflow))


def ci_regenerated_slice100_pins(workflow: Path | None = None) -> dict[str, str]:
    """Return ``{slice100-relative path: sha256}`` for the regenerated pair.

    Args:
        workflow: Workflow YAML. Defaults to ``.github/workflows/ci.yml``.

    Returns:
        Digests from the sha256 pin lines. Each digest is 64 lowercase hex
        characters.

    Raises:
        AssertionError: A pin digest is not 64 lowercase hex characters, or the
            regeneration step fails the same checks as
            :func:`ci_regenerated_slice100_paths`.
    """

    return dict(_ci_regenerated_pins(workflow))


def _overlay_manifest_paths() -> frozenset[str]:
    source_path = _REPO_ROOT / "scripts" / "ci_private_inputs.py"
    tree = ast.parse(source_path.read_text(encoding="utf-8"))
    constants: dict[str, str] = {}
    allowed: ast.AST | None = None
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        if (
            target.id == "PUBLIC_KEY"
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            constants[target.id] = node.value.value
        elif target.id == "ALLOWED_ARTIFACTS":
            allowed = node.value
    if allowed is None:
        raise AssertionError("ALLOWED_ARTIFACTS missing from the overlay manifest")
    return frozenset(_artifact_strings(allowed, constants))


def _artifact_strings(node: ast.AST, constants: Mapping[str, str]) -> set[str]:
    if (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == "frozenset"
    ):
        if len(node.args) != 1:
            raise AssertionError("ALLOWED_ARTIFACTS shape")
        node = node.args[0]
    if not isinstance(node, ast.Set):
        raise AssertionError("ALLOWED_ARTIFACTS shape")
    found: set[str] = set()
    for element in node.elts:
        if isinstance(element, ast.Constant) and isinstance(element.value, str):
            found.add(element.value)
        elif isinstance(element, ast.Name) and element.id in constants:
            found.add(constants[element.id])
        else:
            raise AssertionError("ALLOWED_ARTIFACTS shape")
    return found


def _module_assigns(tree: ast.Module) -> list[tuple[str, ast.AST]]:
    assigns: list[tuple[str, ast.AST]] = []
    for node in tree.body:
        if isinstance(node, ast.Assign):
            assigns.extend(
                (target.id, node.value) for target in node.targets if isinstance(target, ast.Name)
            )
        elif (
            isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and node.value is not None
        ):
            assigns.append((node.target.id, node.value))
    return assigns


def _is_repo_root_expr(node: ast.AST) -> bool:
    if not isinstance(node, ast.Subscript) or not isinstance(node.value, ast.Attribute):
        return False
    if node.value.attr != "parents" or not isinstance(node.value.value, ast.Call):
        return False
    resolve = node.value.value
    if not isinstance(resolve.func, ast.Attribute) or resolve.func.attr != "resolve":
        return False
    path_call = resolve.func.value
    return (
        isinstance(path_call, ast.Call)
        and isinstance(path_call.func, ast.Name)
        and path_call.func.id == "Path"
        and len(path_call.args) == 1
        and isinstance(path_call.args[0], ast.Name)
        and path_call.args[0].id == "__file__"
    )


def _flatten_div(node: ast.AST) -> list[ast.AST]:
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
        return [*_flatten_div(node.left), *_flatten_div(node.right)]
    return [node]


def _repo_root_names(assigns: list[tuple[str, ast.AST]]) -> set[str]:
    roots: set[str] = set()
    changed = True
    while changed:
        changed = False
        for name, value in assigns:
            if name in roots:
                continue
            if _is_repo_root_expr(value) or (isinstance(value, ast.Name) and value.id in roots):
                roots.add(name)
                changed = True
    return roots


def _resolve_slice100_chain(
    node: ast.AST,
    roots: set[str],
    bindings: Mapping[str, tuple[str, ...]],
) -> tuple[str, ...] | None:
    if (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == "with_name"
        and len(node.args) == 1
        and isinstance(node.args[0], ast.Constant)
        and isinstance(node.args[0].value, str)
    ):
        base = _resolve_slice100_chain(node.func.value, roots, bindings)
        if base is None:
            return None
        return (*base[:-1], node.args[0].value)
    parts = _flatten_div(node)
    out: list[str] = []
    saw_root = False
    for index, part in enumerate(parts):
        if isinstance(part, ast.Constant) and isinstance(part.value, str):
            out.append(part.value)
            continue
        if isinstance(part, ast.Name) and part.id in roots:
            saw_root = True
            continue
        if isinstance(part, ast.Name) and part.id in bindings:
            bound = bindings[part.id]
            saw_root = saw_root or (bool(bound) and bound[0] == ".local_reports")
            out.extend(bound)
            continue
        if index == 0 and isinstance(part, ast.Name):
            return None
        return None
    if ".local_reports" not in out or "slice100" not in out:
        return None
    if not saw_root and (not out or out[0] != ".local_reports"):
        return None
    start = out.index(".local_reports")
    return tuple(out[start:])


def _slice100_bindings(
    assigns: list[tuple[str, ast.AST]],
    roots: set[str],
) -> dict[str, tuple[str, ...]]:
    bindings: dict[str, tuple[str, ...]] = {}
    changed = True
    while changed:
        changed = False
        for name, value in assigns:
            if name in bindings:
                continue
            resolved = _resolve_slice100_chain(value, roots, bindings)
            if resolved is not None:
                bindings[name] = resolved
                changed = True
    return bindings


def _relative_slice100(parts: tuple[str, ...]) -> str | None:
    prefix = (".local_reports", "slice100")
    if len(parts) <= len(prefix) or parts[: len(prefix)] != prefix:
        return None
    relative = "/".join(parts[len(prefix) :])
    if "." not in relative.rsplit("/", 1)[-1]:
        return None
    return relative


def _negated_exists_name(test: ast.AST) -> str | None:
    if not isinstance(test, ast.UnaryOp) or not isinstance(test.op, ast.Not):
        return None
    call = test.operand
    if (
        isinstance(call, ast.Call)
        and isinstance(call.func, ast.Attribute)
        and call.func.attr == "exists"
        and not call.args
        and isinstance(call.func.value, ast.Name)
    ):
        return call.func.value.id
    return None


def _consumed_slice100_paths(tree: ast.Module) -> set[str]:
    assigns = _module_assigns(tree)
    roots = _repo_root_names(assigns)
    bindings = _slice100_bindings(assigns, roots)
    loaded_names: set[str] = set()

    class _Uses(ast.NodeVisitor):
        def visit_Assert(self, node: ast.Assert) -> None:
            if _negated_exists_name(node.test) is not None:
                if node.msg is not None:
                    self.visit(node.msg)
                return
            self.generic_visit(node)

        def visit_Name(self, node: ast.Name) -> None:
            if isinstance(node.ctx, ast.Load):
                loaded_names.add(node.id)

    _Uses().visit(tree)
    consumed: set[str] = set()
    for name, parts in bindings.items():
        if name not in loaded_names:
            continue
        relative = _relative_slice100(parts)
        if relative is not None:
            consumed.add(relative)
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Constant)
            and isinstance(node.value, str)
            and node.value.startswith(_OVERLAY_PREFIX)
            and "\n" not in node.value
        ):
            relative = node.value[len(_OVERLAY_PREFIX) :]
            if "." in relative.rsplit("/", 1)[-1]:
                consumed.add(relative)
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        if node.func.attr not in _READ_METHODS:
            continue
        resolved = _resolve_slice100_chain(node.func.value, roots, bindings)
        if resolved is None:
            continue
        relative = _relative_slice100(resolved)
        if relative is not None:
            consumed.add(relative)
    return consumed


def _functions(tree: ast.Module) -> dict[str, ast.FunctionDef]:
    return {node.name: node for node in ast.walk(tree) if isinstance(node, ast.FunctionDef)}


def _loaded_names(fn: ast.AST) -> set[str]:
    return {
        node.id
        for node in ast.walk(fn)
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load)
    }


def _string_constants(fn: ast.AST) -> set[str]:
    return {
        node.value
        for node in ast.walk(fn)
        if isinstance(node, ast.Constant) and isinstance(node.value, str)
    }


def _calls_skip(fn: ast.AST) -> bool:
    for node in ast.walk(fn):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "skip"
        ):
            return True
    return False


def _function_reads_slice100_file(
    fn: ast.AST,
    bindings: Mapping[str, tuple[str, ...]],
) -> bool:
    for name in _loaded_names(fn):
        if _relative_slice100(bindings.get(name, ())) is not None:
            return True
    return any(
        value.startswith(_OVERLAY_PREFIX) and "\n" not in value for value in _string_constants(fn)
    )


def _workflow_file(workflow: Path | None) -> Path:
    if workflow is None:
        return _DEFAULT_WORKFLOW
    return workflow


def _as_mapping(value: object, message: str) -> Mapping[str, object]:
    if not isinstance(value, dict):
        raise AssertionError(message)
    return value


def _check_steps(workflow: Path | None) -> list[object]:
    loaded = yaml.safe_load(_workflow_file(workflow).read_text(encoding="utf-8"))
    jobs = _as_mapping(loaded, "workflow root must be a mapping").get("jobs")
    check = _as_mapping(jobs, "workflow jobs missing").get("check")
    steps = _as_mapping(check, "check job missing").get("steps")
    if not isinstance(steps, list):
        raise AssertionError("check steps missing")
    return steps


def _run_has_mkdir_line(run: str) -> bool:
    return any(line.strip() == _V27_CANDIDATE_MKDIR for line in run.splitlines())


def _regeneration_run(workflow: Path | None) -> str:
    matches: list[str] = []
    for step in _check_steps(workflow):
        if not isinstance(step, dict):
            continue
        run = step.get("run")
        if isinstance(run, str) and _run_has_mkdir_line(run):
            matches.append(run)
    if len(matches) != 1:
        raise AssertionError("expected exactly one v27 CI regeneration step")
    return matches[0]


def _relative_overlay_file(path: str) -> str:
    cleaned = path.strip("'\"")
    if not cleaned.startswith(_OVERLAY_PREFIX):
        raise AssertionError("CI-regenerated path is outside slice100")
    relative = cleaned[len(_OVERLAY_PREFIX) :]
    if "." not in relative.rsplit("/", 1)[-1]:
        raise AssertionError("CI-regenerated path is not a slice100 file")
    return relative


def _flag_arguments(line: str, flag: str) -> list[str]:
    parts = line.split()
    found: list[str] = []
    for index, part in enumerate(parts):
        if part != flag:
            continue
        if index + 1 >= len(parts):
            raise AssertionError("CI flag is missing its path")
        found.append(parts[index + 1])
    return found


def _staging_output_paths(run: str, script: str) -> frozenset[str]:
    """Return ``--staging-output`` paths for ``script``.

    The generate script writes its contract-hash fixture through that same flag.
    """

    found: set[str] = set()
    for line in run.splitlines():
        if script not in line:
            continue
        arguments = _flag_arguments(line, _STAGING_OUTPUT_FLAG)
        if not arguments:
            raise AssertionError("CI regeneration command is missing --staging-output")
        found.update(_relative_overlay_file(argument) for argument in arguments)
    return frozenset(found)


def _pin_entries(run: str) -> dict[str, str]:
    pins: dict[str, str] = {}
    for raw_line in run.splitlines():
        line = raw_line.strip()
        if "sha256sum" not in line or _OVERLAY_PREFIX not in line:
            continue
        pairs = [
            (match.group("digest"), _relative_overlay_file(match.group("path")))
            for match in _PIN_PAIR.finditer(line)
        ]
        paths = [_relative_overlay_file(match.group(0)) for match in _PIN_PATH.finditer(line)]
        if [path for _digest, path in pairs] != paths:
            raise AssertionError("sha256 pin line lacks a 64-hex digest")
        for digest, relative in pairs:
            if _SHA256_HEX.fullmatch(digest) is None:
                raise AssertionError("sha256 pin line lacks a 64-hex digest")
            previous = pins.get(relative)
            if previous is not None and previous != digest:
                raise AssertionError("sha256 pin lines disagree")
            pins[relative] = digest
    return pins


def _ci_regenerated_pins(workflow: Path | None) -> dict[str, str]:
    run = _regeneration_run(workflow)
    materialize_paths = _staging_output_paths(run, _MATERIALIZE_V27_SCRIPT)
    generate_paths = _staging_output_paths(run, _GENERATE_V27_SCRIPT)
    pins = _pin_entries(run)
    produced = materialize_paths | generate_paths
    if not materialize_paths or not generate_paths or produced != frozenset(pins):
        raise AssertionError("CI-regenerated sources disagree")
    if len(produced) != _CI_REGENERATED_PATH_COUNT:
        raise AssertionError("CI-regenerated set must have exactly two paths")
    return pins
